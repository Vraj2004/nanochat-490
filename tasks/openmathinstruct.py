"""
OpenMathInstruct-2 by NVIDIA: math problems with solutions generated by Llama-3.1-405B-Instruct.
https://huggingface.co/datasets/nvidia/OpenMathInstruct-2

We use the train_1M split and keep only the GSM8K-sourced rows (problem_source gsm8k or
augmented_gsm8k, 153K rows). Solutions end in \\boxed{N}; we append "#### N" (from the
expected_answer column) so they end like GSM8K.
"""

import pyarrow as pa
import pyarrow.compute as pc
from tasks.common import Task, load_hub_dataset, HubDataset

class OpenMathInstruct(Task):
    """ OpenMathInstruct-2 (train_1M), GSM8K-sourced rows only. 153K rows. """

    def __init__(self, **kwargs):
        super().__init__(**kwargs)
        table = load_hub_dataset("nvidia/OpenMathInstruct-2", split="train_1M").table
        table = table.filter(pc.is_in(table["problem_source"], value_set=pa.array(["gsm8k", "augmented_gsm8k"])))
        self.ds = HubDataset(table).shuffle(seed=42)

    def num_examples(self):
        return len(self.ds)

    def get_example(self, index):
        row = self.ds[index]
        solution = f"{row['generated_solution'].rstrip()}\n#### {row['expected_answer']}"
        messages = [
            {"role": "user", "content": row["problem"]},
            {"role": "assistant", "content": solution},
        ]
        return {"messages": messages}
